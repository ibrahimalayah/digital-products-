// Records which optional brand photos exist in public/brand, so pages can use
// them when present and fall back to drawn artwork when not.
import fs from "node:fs";

const names = ["hero", "auth", "store"];
const found = Object.fromEntries(
  names.map((n) => {
    const file = ["jpg", "jpeg", "png", "webp"].map((ext) => `${n}.${ext}`).find((f) => fs.existsSync(`public/brand/${f}`));
    return [n, file ? `/brand/${file}` : null];
  }),
);
fs.writeFileSync(
  "src/lib/brand.generated.ts",
  `// Generated by scripts/brand.mjs. Do not edit.\nexport const BRAND: { hero: string | null; auth: string | null; store: string | null } = ${JSON.stringify(found, null, 2)};\n`,
);
console.log("[brand]", JSON.stringify(found));
